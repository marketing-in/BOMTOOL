/**
 * Letter shapes of the stroke fonts CAD tools draw silkscreen text with, as plain polylines: what the silkscreen
 * reader compares a drawn glyph with. One character may have several shapes (one per font that draws it
 * differently). Units: the capital height is 100, the baseline 0, x runs from the glyph's left edge.
 *
 * `d` is "x,y x,y ...|x,y ..." — one polyline per pen-down.
 *
 * The three CAD fonts below were measured off real Gerber exports and hold only the characters those boards print
 * (no W, X or Z in every one, no lower case). The plain skeleton has every character and fills the gaps: a letter
 * shape differs less between fonts than two letters do. A shape is only listed where the font draws the character
 * unlike the fonts before it.
 */
export type SilkGlyph = { ch: string; d: string };

