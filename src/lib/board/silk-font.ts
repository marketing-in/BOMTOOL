/** The skeleton's grid brought to the common units (capital height 100). */
const scaled = (shape: string) =>
  shape
    .split("|")
    .map((line) => line.split(" ").map((p) => p.split(",").map((n) => Math.round((Number(n) * 100) / 6)).join(",")).join(" "))
    .join("|");

const glyphs = (font: Record<string, string[]>, each: (shape: string) => string = (shape) => shape): SilkGlyph[] =>
  Object.entries(font).flatMap(([ch, shapes]) => shapes.map((shape) => ({ ch, d: each(shape) })));

/** Every shape the reader knows, the measured fonts first. */
export const SILK_GLYPHS: SilkGlyph[] = [...glyphs(ALTIUM), ...glyphs(SANS), ...glyphs(ALLEGRO), ...glyphs(PLAIN, scaled)];
