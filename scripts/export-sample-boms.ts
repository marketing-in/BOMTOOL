/** Writes the seeded sample BoMs as customer-style CSV files for Phase 1 upload testing. */
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { BOMS, bomToRows } from "../prisma/seed-data/boms";

const outDir = path.resolve(process.cwd(), "samples/boms");
mkdirSync(outDir, { recursive: true });

const esc = (v: string | number | undefined) => {
  const s = v === undefined ? "" : String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

for (const b of BOMS) {
  const rows = bomToRows(b);
  const csv = rows.map((r) => r.map(esc).join(",")).join("\r\n") + "\r\n";
  const file = path.join(outDir, `${b.assemblyPartNumber}_rev${b.revision}.csv`);
  writeFileSync(file, csv, "utf8");
  console.log(`wrote ${path.relative(process.cwd(), file)} (${rows.length - 1} lines)`);
}

